def lookup(code):
    """单值查询，未命中返回空串"""
    if code is None or (isinstance(code, float) and pd_isnan(code)):
        return ''
    return DIL_EI_MAP.get(str(code).strip(), '')


def lookup_with_warning(series):
    """批量查询，未命中返回原值 + warning（不静默吞）"""
    import pandas as pd
    result = series.astype(str).map(DIL_EI_MAP)
    missing = series[result.isna() & series.notna()]
    if len(missing) > 0:
        unique_missing = sorted(set(missing.astype(str)))
        print(f'[WARNING] 地类代码未命中 {len(unique_missing)} 个: {unique_missing}')
    return result.fillna('')


def pd_isnan(x):
    """检查 NaN，不依赖 pandas 也能用"""
    try:
        return x != x
    except Exception:
        return False


